export function isSignInProvider(value: unknown): value is SignInProvider {
  return value === "google" || value === "apple" || value === "github" || value === "discord";
}

/**
 * Brand marks, the one place the panel draws its own svg: Lucide has no
 * brand logos (design-system.md section 12). Sized by CSS (`.provider-mark`,
 * 16px; `small` is 12px, for inline beside text), like every icon.
 */
export const ProviderMark: React.FC<{ provider: SignInProvider; small?: boolean; className?: string }> = ({
  provider,
  small = false,
  className,
}) => (
  <svg
    viewBox={GLYPHS[provider].viewBox}
    aria-hidden="true"
    focusable="false"
    className={cn("provider-mark", small && "is-small", className)}
  >
    <path fill="currentColor" d={GLYPHS[provider].d} />
  </svg>
);

export type BrandLogoId = SignInProvider | "stripe" | "lemonsqueezy" | "razorpay";

/** The full-colour logo tiles in `public/`, one per provider and gateway. */
const LOGO_FILES: Record<BrandLogoId, string> = {
  google: "/google.svg",
  apple: "/apple.svg",
  github: "/github.svg",
  discord: "/discord.svg",
  stripe: "/Stripe.svg",
  lemonsqueezy: "/lemon-squeezy.svg",
  razorpay: "/razorpay.png",
};

export function isBrandLogoId(value: unknown): value is BrandLogoId {
  return typeof value === "string" && Object.prototype.hasOwnProperty.call(LOGO_FILES, value);
}

/**
 * A provider's or gateway's logo tile: the integration card's icon and the
 * sheet's 32px icon tile. A file, not an inline svg, so it fills the tile it
 * sits in (`.brand-logo`).
 */
export const BrandLogo: React.FC<{ brand: BrandLogoId; className?: string }> = ({ brand, className }) => (
  <img src={LOGO_FILES[brand]} alt="" aria-hidden="true" draggable={false} className={cn("brand-logo", className)} />
);
